#!/usr/bin/env python3
"""Render task-gen trajectory JSONL files as a self-contained local HTML viewer.

This is only a renderer. It expects a JSONL list of trajectories that has
already been sampled elsewhere.

The checkpoint-10 sample JSONL we made earlier was produced by:

1. Pulling Zhichao's successful Qwen3.5-9B runs from the `fleet-task-gen`
   W&B project, excluding 35B runs.
2. Indexing rollout files from
   `s3://skyrl-trajectories/rollouts/{trainer_run_name}/global_step_N.jsonl`.
3. Keeping rollout `global_step_11` files whose producer checkpoint was the
   persisted S3 checkpoint
   `fleet-task-gen/Qwen3.5-9B/{trainer_run_name}/global_step_10/`.
4. Writing representative records to `sampled_records.jsonl`, annotated with
   fields such as `trainer_run_name`, `wandb_display_name`, `global_step`,
   `source_weight_step`, `source_checkpoint_label`, `s3_uri`,
   `local_full_file`, `env_key`, `reward`, `stop_reason`, `turns`, `tokens`,
   `prompt`, `text`, and `task_excerpt`.

It can also render:
- Fleet API transcript JSON files with top-level `task`, `transcript`, and
  `verifier_execution` fields.
- SkyRL eval JSONL dumps with `input_prompt`, `output_response`, and `score`.

Important provenance detail: rollout `global_step_N` is dumped before training
step N, so it was generated by weights after step N-1. In other words, the
"checkpoint 10" samples are rollout `global_step_11` records with
`source_weight_step == 10`, not samples read from checkpoint files themselves.

Examples:
    uv run --no-project --python 3.14 \
        python scripts/render_task_gen_trajectories.py \
        outputs/.../sampled_records.jsonl \
        --output outputs/.../viewer.html

Use `--no-project` because this renderer is stdlib-only. A plain `uv run`
from the SkyRL repo will try to sync the full project environment, including
torch. Python 3.14 is the newest local uv Python compatible with the torch
wheel tags in this repo; Python 3.15 beta is too new for that torch build.

The generated HTML is standalone and can be opened directly in a browser.
The script uses only Python's standard library.
"""

