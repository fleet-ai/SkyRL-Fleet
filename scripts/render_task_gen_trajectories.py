def _render_html(records: list[dict[str, Any]], title: str) -> str:
    return (
        HTML_TEMPLATE.replace("__TITLE__", html.escape(title, quote=True))
        .replace("__DATA_JSON__", _safe_json(records))
        .replace("__SUMMARY_JSON__", _safe_json(_summary(records)))
    )


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Render task-gen trajectory JSONL files")
    parser.add_argument("input", nargs="+", type=Path, help="Input JSONL, JSON transcript, or directory")
    parser.add_argument("--output", "-o", type=Path, required=True, help="Output HTML path")
    parser.add_argument("--title", default="Task-Gen Trajectory Viewer", help="HTML page title")
    parser.add_argument("--max-records", type=int, default=None, help="Render at most this many input records")
    return parser.parse_args()


def main() -> None:
    args = _parse_args()
    records: list[dict[str, Any]] = []
    for path in args.input:
        records.extend(_read_input(path))
    if args.max_records is not None:
        records = records[: args.max_records]

    normalised = _normalise(records)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(_render_html(normalised, args.title), encoding="utf-8")
    print(f"Rendered {len(normalised)} trajectories to {args.output}")


if __name__ == "__main__":
    main()
