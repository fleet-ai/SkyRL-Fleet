INTERNAL_PREFIX = "_viewer_"


def _ids_from_transcript_filename(path: Path) -> dict[str, str]:
    uuids = re.findall(
        r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}",
        path.stem,
        flags=re.IGNORECASE,
    )
    ids: dict[str, str] = {}
    if len(uuids) >= 1:
        ids["job_id"] = uuids[0]
    if len(uuids) >= 2:
        ids["session_id"] = uuids[1]
    return ids


def _format_transcript(transcript: Any) -> str:
    if not isinstance(transcript, list):
        return ""

    chunks: list[str] = []
    for i, message in enumerate(transcript, 1):
        if not isinstance(message, dict):
            chunks.append(f"[{i}] {message}")
            continue

        role = message.get("role", "unknown")
        chunks.append(f"[{i}] {role}")

        content = message.get("content")
        if content not in (None, ""):
            chunks.append(str(content))

        tool_calls = message.get("tool_calls")
        if tool_calls:
            chunks.append("tool_calls:")
            chunks.append(json.dumps(tool_calls, ensure_ascii=False, indent=2))

        tool_call_id = message.get("tool_call_id")
        if tool_call_id:
            chunks.append(f"tool_call_id: {tool_call_id}")

        chunks.append("")

    return "\n".join(chunks).strip()


def _normalise_json_record(record: dict[str, Any], path: Path, line_no: int) -> dict[str, Any]:
    record = dict(record)
    record.setdefault("_source_file", str(path))
    record.setdefault("_source_line", line_no)

    for score_key in ("reward", "score"):
        value = record.get(score_key)
        if isinstance(value, list):
            record[f"{score_key}_tokens"] = value
            record[score_key] = sum(float(x or 0.0) for x in value)

    env_extras = record.get("env_extras")
    if isinstance(env_extras, dict):
        record.setdefault("data_source", env_extras.get("data_source"))
        record.setdefault("env_key", env_extras.get("env_key") or env_extras.get("data_source"))

    if "output_response" in record and "text" not in record:
        record["text"] = record.get("output_response")

    if isinstance(record.get("transcript"), list):
        task = record.get("task") if isinstance(record.get("task"), dict) else {}
        instance = record.get("instance") if isinstance(record.get("instance"), dict) else {}
        verifier_execution = (
            record.get("verifier_execution")
            if isinstance(record.get("verifier_execution"), dict)
            else {}
        )

        flattened = {
            **record,
            **_ids_from_transcript_filename(path),
            "record_type": "fleet_solver_transcript",
            "task_key": task.get("key"),
            "env_key": task.get("env_id") or instance.get("env_key"),
            "data_source": task.get("env_id") or instance.get("env_key"),
            "prompt": task.get("prompt"),
            "input_prompt": task.get("prompt"),
            "verifier": task.get("verifier_func"),
            "reward": verifier_execution.get("score"),
            "score": verifier_execution.get("score"),
            "verifier_success": verifier_execution.get("success"),
            "verifier_stdout": verifier_execution.get("stdout"),
            "text": _format_transcript(record.get("transcript")),
        }
        return flattened

    return record


def _read_json(path: Path) -> list[dict[str, Any]]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise SystemExit(f"{path}: invalid JSON: {exc}") from exc

    if isinstance(value, dict):
        return [_normalise_json_record(value, path, 1)]
    if isinstance(value, list):
        records: list[dict[str, Any]] = []
        for idx, item in enumerate(value, 1):
            if not isinstance(item, dict):
                raise SystemExit(f"{path}:{idx}: expected a JSON object")
            records.append(_normalise_json_record(item, path, idx))
        return records
    raise SystemExit(f"{path}: expected a JSON object, JSON array, or JSONL file")


def _read_jsonl(path: Path) -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    with path.open("r", encoding="utf-8") as handle:
        for line_no, line in enumerate(handle, 1):
            line = line.strip()
            if not line:
                continue
            try:
                record = json.loads(line)
            except json.JSONDecodeError as exc:
                raise SystemExit(f"{path}:{line_no}: invalid JSON: {exc}") from exc
            if not isinstance(record, dict):
                raise SystemExit(f"{path}:{line_no}: expected a JSON object")
            records.append(_normalise_json_record(record, path, line_no))
    return records


def _read_input(path: Path) -> list[dict[str, Any]]:
    if path.is_dir():
        records: list[dict[str, Any]] = []
        for child in sorted(path.glob("*.json")) + sorted(path.glob("*.jsonl")):
            records.extend(_read_input(child))
        return records
    if path.suffix == ".json":
        return _read_json(path)
    return _read_jsonl(path)


def _number(value: Any) -> float | None:
    if value is None or value == "":
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def _compact_text(value: Any, max_chars: int = 1200) -> str:
    if not isinstance(value, str):
        return ""
    value = re.sub(r"\s+", " ", value).strip()
    if len(value) <= max_chars:
        return value
    return value[: max_chars - 1] + "..."


def _extract_tag(text: Any, tag: str) -> str:
    if not isinstance(text, str):
        return ""
    match = re.search(rf"<{tag}>(.*?)</{tag}>", text, flags=re.DOTALL)
    return match.group(1).strip() if match else ""


def _extract_task_excerpt(record: dict[str, Any]) -> str:
    explicit = record.get("task_excerpt")
    if isinstance(explicit, str) and explicit.strip():
        return _compact_text(explicit)

    for key in ("input_prompt", "prompt"):
        value = record.get(key)
        if isinstance(value, str) and value.strip():
            return _compact_text(value)

    task = record.get("task")
    if isinstance(task, dict) and isinstance(task.get("prompt"), str):
        return _compact_text(task["prompt"])

    text = record.get("text")
    task = _extract_tag(text, "task")
    prompt = _extract_tag(task or text, "prompt")
    output_response = record.get("output_response")
    return _compact_text(prompt or task or text or output_response)


def _run_name(record: dict[str, Any]) -> str:
    for key in (
        "trainer_run_name",
        "wandb_display_name",
        "run_name",
        "wandb_run_id",
        "job_id",
        "session_id",
        "task_key",
    ):
        value = record.get(key)
        if value not in (None, ""):
            return str(value)
    return "unknown"


def _normalise(records: list[dict[str, Any]]) -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    for index, record in enumerate(records, 1):
        item = dict(record)
        item[f"{INTERNAL_PREFIX}input_index"] = index
        item[f"{INTERNAL_PREFIX}run_name"] = _run_name(item)
        item[f"{INTERNAL_PREFIX}reward_number"] = _number(item.get("reward", item.get("score")))
        item[f"{INTERNAL_PREFIX}global_step_number"] = _number(item.get("global_step"))
        item[f"{INTERNAL_PREFIX}tokens_number"] = _number(item.get("tokens"))
        item[f"{INTERNAL_PREFIX}turns_number"] = _number(item.get("turns"))
        item[f"{INTERNAL_PREFIX}task_excerpt"] = _extract_task_excerpt(item)
        out.append(item)
    return out


def _safe_json(value: Any) -> str:
    # Keep embedded JSON from terminating the script tag.
    return (
        json.dumps(value, ensure_ascii=False)
        .replace("<", "\\u003c")
        .replace(">", "\\u003e")
        .replace("&", "\\u0026")
    )


def _summary(records: list[dict[str, Any]]) -> dict[str, Any]:
    rewards = [r[f"{INTERNAL_PREFIX}reward_number"] for r in records if r.get(f"{INTERNAL_PREFIX}reward_number") is not None]
    positive = [r for r in records if (r.get(f"{INTERNAL_PREFIX}reward_number") or 0) > 0]
    envs = sorted({str(r.get("env_key") or r.get("data_source") or "unknown") for r in records})
    runs = sorted({str(r.get(f"{INTERNAL_PREFIX}run_name") or "unknown") for r in records})
    return {
        "count": len(records),
        "positive_count": len(positive),
        "reward_min": min(rewards) if rewards else None,
        "reward_max": max(rewards) if rewards else None,
        "env_count": len(envs),
        "run_count": len(runs),
    }


